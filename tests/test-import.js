'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { parseInvoiceWorkbook } = require('../invoice-import');
const fixture = JSON.parse(fs.readFileSync(__dirname + '/fixture-synthetic.json', 'utf8'));
const XLSXMock = { utils: { sheet_to_json(sheet) { return sheet.rows; } } };
const book = { SheetNames: Object.keys(fixture), Sheets: Object.fromEntries(Object.entries(fixture).map(([name, rows]) => [name, { rows }])) };
const got = parseInvoiceWorkbook(book, XLSXMock);
assert.equal(got.ok, true);
assert.equal(got.invoiceNo, '99999');
assert.equal(got.invoiceDate, '1405/07/06');
assert.equal(got.customerName, 'جناب آقای مشتری نمونه (تست)');
assert.deepEqual(got.items.map(x => [x.code, x.qty]), [['11401', 50], ['18501', 50], ['25802', 20]]);
assert.equal(got.totalQty, 120);
assert.equal(got.declaredTotal, 120);
assert.equal(got.totalMatchesDeclared, true);
console.log('PASS: invoice number/date/customer extracted');
console.log('PASS: 3 item rows and quantities 50, 50, 20');
console.log('PASS: sum 120 matches declared total 120');
